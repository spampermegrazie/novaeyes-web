export function markOutline(): [number, number][] {
  const v = OUTLINE.split(",").map(Number);
  const pts: [number, number][] = [];
  let x = 0;
  let y = 0;
  for (let i = 0; i < v.length; i += 2) {
    x += v[i] / 2;
    y += v[i + 1] / 2;
    pts.push([x, y]);
  }
  return pts;
}
